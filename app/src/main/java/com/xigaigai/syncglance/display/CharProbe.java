package com.xigaigai.syncglance.display;

/**
 * 字符探测表：把能想到的字符集分组，逐组发到车机上，看哪些真有字形。
 *
 * <h3>为什么要分组试</h3>
 * 实测 ⧗ ▶ ⏸ 和八方向箭头在 SYNC 1.1 / MFD4 上全部渲染成一个圆点，
 * 说明车机点阵字库比想象的小得多。但「小」到什么程度不知道 ——
 * 是只有 ASCII？还是 GB2312？还是带了 JIS 假名？
 *
 * <h3>几个关键假设（这轮要验证的）</h3>
 * <ol>
 *   <li><b>GB2312 里是有日文假名的</b>（第 4、5 区就是平假名/片假名）。
 *       如果车机字库是按 GB2312 建的，平假名和片假名应该<b>有字形</b>，
 *       哪怕制表符和箭头没有。这一条最容易意外成功。</li>
 *   <li><b>半角片假名是另一套编码</b>（U+FF61–FF9F，源自 JIS X 0201），
 *       GB2312 里没有，GBK 才补上。如果车机只做到 GB2312，
 *       半角片假名会全灭而全角假名正常 —— 这能反推字库范围。</li>
 *   <li><b>CJK 兼容表意文字</b>（U+2F800/U+F900 区）是「同一个汉字的另一个码位」。
 *       老字库按 KS X 1001 / Big5 建表时，某些汉字只存在于兼容区。
 *       所以同一句中文，换个码位可能就有字形了。</li>
 *   <li>全角 ASCII（U+FF01–FF5E）来自 JIS X 0208，也是独立于半角的一套。</li>
 * </ol>
 */
